# Aerospace context: LLM often translates "vehicle" as "车辆"(ground vehicle)
# instead of "飞行器".  Use regex with CJK-aware boundaries to avoid
# replacing inside compound terms like "装甲车辆".
_VEHICLE_RE = re.compile(r'(?<![一-鿿a-zA-Z])车辆(?![一-鿿a-zA-Z])')


def _chinese_normalize(text: str) -> str:
    """Apply Chinese→Chinese post-processing to fix common LLM mistranslations."""
    for wrong, correct in _CHINESE_NORMALIZE.items():
        text = text.replace(wrong, correct)
    text = _VEHICLE_RE.sub("飞行器", text)
    return text


def get_combined_glossary(theme: str | None = None) -> dict[str, str]:
    """Return merged glossary for a given theme name ("news", "aam", or None).

    None returns SHARED only.  "news" / "aam" merge SHARED + theme-specific.
    """
    combined = dict(SHARED)
    theme_lower = theme.lower() if theme else ""
    if theme_lower == "aam":
        combined.update(AAM)
    elif theme_lower == "news":
        combined.update(NEWS)
    return combined


def apply_glossary(text: str, theme: str | None = None) -> str:
    """Replace English source terms with their Chinese translations,
    then apply Chinese→Chinese normalization for common LLM mistranslations.

    The *theme* argument selects which glossary to merge:
      "news" → SHARED + NEWS
      "aam"  → SHARED + AAM
      None   → SHARED only

    Uses letter-based word-boundary lookarounds so longer phrases match
    before shorter ones and subword matches are prevented.
    """
    if not text:
        return text

    key = theme or "shared"
    if key not in _CACHE:
        merged = get_combined_glossary(theme)
        items = _sort_terms(merged)
        lookup = _build_lookup(merged)
        patterns = [_word_boundary_pattern(t) for t, _ in items]
        regex = re.compile("|".join(patterns))
        _CACHE[key] = (regex, lookup)
    else:
        regex, lookup = _CACHE[key]

    def _replacer(match: re.Match) -> str:
        matched = match.group(0)
        # Preserve all-caps abbreviations inside parentheses preceded by
        # Chinese text — standard Chinese format: 全称（缩写）
        if re.match(r'^[A-Z][A-Z0-9\-/]*$', matched):
            pos = match.start()
            before = text[max(0, pos - 60):pos]
            for open_p, close_p in [('（', '）'), ('(', ')')]:
                if open_p in before and close_p not in before.split(open_p)[-1]:
                    before_open = before.rsplit(open_p, 1)[0]
                    if re.search(r'[一-鿿]', before_open[-20:]):
                        return matched
        return lookup.get(matched.lower(), matched)

    text = regex.sub(_replacer, text)
    # Chinese→Chinese normalization for common LLM mistranslations
    text = _chinese_normalize(text)
    return text


def get_prompt_terms(theme: str, max_terms: int = 25) -> str:
    """Get top glossary terms formatted for LLM prompt injection.

    Returns a block of text like:
      Domain Glossary (must follow these translations):
      - "Eglin" (in military context) → 埃格林空军基地
      ...
    Includes short but critical terms (aircraft, missile names) that would
    otherwise be excluded by the length-based sort.
    """
    merged = get_combined_glossary(theme)

    # Short-but-critical terms always included regardless of length ranking.
    # Must match exact glossary keys (case-sensitive).
    _CRITICAL_SHORT_TERMS = {
        "Meteor", "AIM-120", "AIM-9", "AIM-260", "PL-15", "PL-10", "PL-17",
        "IRIS-T", "ASRAAM", "R-77", "R-37", "Su-57", "Su-35", "F-22",
        "F-35", "J-20", "Gripen", "Rafale", "Eurofighter", "Typhoon",
        "ramjet", "scramjet", "hypersonic", "supersonic",
        "ballistic missile",
    }

    items = _sort_terms(merged)
    seen = set()
    selected = []

    # First, include critical short terms if they exist in the glossary
    for term_name, zh in items:
        if term_name in _CRITICAL_SHORT_TERMS and term_name not in seen:
            selected.append((term_name, zh))
            seen.add(term_name)

    # Then fill remaining slots with longest terms not yet included
    for term_name, zh in items:
        if len(selected) >= max_terms:
            break
        if term_name not in seen:
            selected.append((term_name, zh))
            seen.add(term_name)

    lines = ["Domain Glossary (must follow these translations):"]
    for en, zh in selected:
        lines.append(f'- "{en}" → {zh}')
    return "\n".join(lines)
