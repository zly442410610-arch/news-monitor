# ── Regex engine ────────────────────────────────────────────────────────────

_CACHE: dict[str, tuple[Pattern, dict[str, str]]] = {}


def _word_boundary_pattern(term: str) -> str:
    """Build a regex pattern that matches *term* as a standalone word.

    Uses letter-based lookarounds so that "ramjet" does not match inside
    "scramjet" and "AIM-120" matches "AIM-120" but not "AIM-120C".
    """
    escaped = re.escape(term)
    return rf'(?<![a-zA-Z]){escaped}(?![a-zA-Z])'


def _build_lookup(terms: dict[str, str]) -> dict[str, str]:
    """Build a case-folded lookup keyed by lowercase of source term."""
    return {k.lower(): v for k, v in terms.items()}


def _sort_terms(terms: dict[str, str]) -> list[tuple[str, str]]:
    """Sort terms longest-first so longer phrases match before shorter ones."""
    return sorted(terms.items(), key=lambda x: -len(x[0]))


